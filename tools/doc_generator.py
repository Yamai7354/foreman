def generate_documentation(project_path: str, output: Optional[str], format: str):
    """Generate comprehensive documentation for a project."""
    project_path = Path(project_path)
    log_info(f"Analyzing project: {project_path.name}")

    info = analyze_project(project_path)

    # Display summary
    console.print(f"\n[bold]Project:[/bold] {info['name']}")
    console.print(f"[bold]Type:[/bold] {info['type']}")
    console.print(f"[bold]Python Files:[/bold] {len(info['files'])}")
    console.print(f"[bold]Classes:[/bold] {len(info['classes'])}")
    console.print(f"[bold]Functions:[/bold] {len(info['functions'])}")

    # Generate docs
    output_path = Path(output) if output else project_path / "docs"
    output_path.mkdir(parents=True, exist_ok=True)

    # Write API reference
    api_doc = generate_api_markdown(info)
    api_file = output_path / "API.md"
    api_file.write_text(api_doc, encoding="utf-8")
    log_success(f"API docs written to: {api_file}")

    # Write project overview
    overview = f"# {info['name']} - Project Overview\n\n"
    overview += f"**Type:** {info['type']}\n\n"
    overview += "## Structure\n\n```\n" + generate_structure_tree(project_path) + "\n```\n"

    overview_file = output_path / "OVERVIEW.md"
    overview_file.write_text(overview, encoding="utf-8")
    log_success(f"Overview written to: {overview_file}")


def generate_readme(project_path: str, template: str = "default"):
    """Generate a README.md for a project."""
    project_path = Path(project_path)
    log_info(f"Generating README for: {project_path.name}")

    info = analyze_project(project_path)

    # Detect features from code
    features = []
    for cls in info["classes"][:5]:
        if cls["docstring"]:
            features.append(cls["docstring"].split('\n')[0])
    for func in info["functions"][:5]:
        if func["docstring"]:
            features.append(func["docstring"].split('\n')[0])

    if not features:
        features = ["Feature 1 - Add description", "Feature 2 - Add description"]

    # Generate install command based on project type
    if info["type"] == "python":
        install_command = "pip install -e ."
        code_lang = "python"
        usage_example = f"from {info['name']} import main\n\nmain()"
    elif info["type"] == "node":
        install_command = "npm install"
        code_lang = "javascript"
        usage_example = f"const {info['name']} = require('{info['name']}');"
    else:
        install_command = "# Add installation instructions"
        code_lang = "bash"
        usage_example = "# Add usage example"

    # Render template
    tmpl = Template(DEFAULT_README_TEMPLATE)
    readme_content = tmpl.render(
        project_name=info["name"],
        description=f"A {info['type']} project.",
        features=features,
        install_command=install_command,
        code_lang=code_lang,
        usage_example=usage_example,
        structure=generate_structure_tree(project_path, max_depth=2),
        api_reference="See [API.md](docs/API.md) for detailed API documentation." if info["classes"] or info["functions"] else "",
        license="MIT",
        generated_date=datetime.now().strftime("%Y-%m-%d")
    )

    # Write README
    readme_path = project_path / "README.md"

    if readme_path.exists():
        log_warning("README.md already exists. Writing to README.generated.md")
        readme_path = project_path / "README.generated.md"

    readme_path.write_text(readme_content, encoding="utf-8")
    log_success(f"README written to: {readme_path}")

    # Display preview
    display_panel("README Preview", readme_content[:1000] + "..." if len(readme_content) > 1000 else readme_content)


def generate_api_docs(project_path: str, output: Optional[str]):
    """Extract API documentation from code."""
    project_path = Path(project_path)
    log_info(f"Extracting API docs from: {project_path.name}")

    info = analyze_project(project_path)
    api_doc = generate_api_markdown(info)

    # Write output
    if output:
        output_path = Path(output)
    else:
        output_path = project_path / "docs" / "API.md"

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(api_doc, encoding="utf-8")

    log_success(f"API documentation written to: {output_path}")
    console.print(f"\n[bold]Classes documented:[/bold] {len(info['classes'])}")
    console.print(f"[bold]Functions documented:[/bold] {len(info['functions'])}")


def generate_api_markdown(info: dict) -> str:
    """Generate API reference in Markdown format."""
    lines = [
        f"# {info['name']} - API Reference",
        "",
        f"*Auto-generated on {datetime.now().strftime('%Y-%m-%d')}*",
        "",
    ]

    # Classes section
    if info["classes"]:
        lines.extend(["## Classes", ""])

        for cls in info["classes"]:
            lines.append(f"### `{cls['name']}`")
            lines.append(f"*Defined in: {cls['file']}:{cls['lineno']}*")
            lines.append("")

            if cls["docstring"]:
                lines.append(cls["docstring"])
                lines.append("")

            if cls["methods"]:
                lines.append("**Methods:**")
                lines.append("")
                for method in cls["methods"]:
                    args_str = ", ".join(method["args"]) if method["args"] else ""
                    lines.append(f"#### `{method['name']}({args_str})`")
                    if method["docstring"]:
                        lines.append(f"> {method['docstring']}")
                    lines.append("")

            lines.append("---")
            lines.append("")

    # Functions section
    if info["functions"]:
        lines.extend(["## Functions", ""])

        for func in info["functions"]:
            args_str = ", ".join(func["args"]) if func["args"] else ""
            lines.append(f"### `{func['name']}({args_str})`")
            lines.append(f"*Defined in: {func['file']}:{func['lineno']}*")
            lines.append("")

            if func["docstring"]:
                lines.append(func["docstring"])
            lines.append("")
            lines.append("---")
            lines.append("")

    return "\n".join(lines)
