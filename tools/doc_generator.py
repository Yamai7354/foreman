class PythonAnalyzer:
    """Analyze Python files for documentation extraction."""

    def __init__(self, file_path: Path):
        self.file_path = file_path
        self.content = read_file_safely(file_path) or ""
        self.tree = None
        try:
            self.tree = ast.parse(self.content)
        except SyntaxError:
            pass

    def get_module_docstring(self) -> Optional[str]:
        """Get the module-level docstring."""
        if self.tree and self.tree.body:
            first = self.tree.body[0]
            if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant):
                return first.value.value
        return None

    def get_classes(self) -> list[dict]:
        """Get all classes with their docstrings and methods."""
        if not self.tree:
            return []

        classes = []
        for node in ast.walk(self.tree):
            if isinstance(node, ast.ClassDef):
                methods = []
                for item in node.body:
                    if isinstance(item, ast.FunctionDef):
                        methods.append({
                            "name": item.name,
                            "docstring": ast.get_docstring(item),
                            "args": [arg.arg for arg in item.args.args if arg.arg != "self"],
                            "lineno": item.lineno
                        })

                classes.append({
                    "name": node.name,
                    "docstring": ast.get_docstring(node),
                    "methods": methods,
                    "lineno": node.lineno
                })
        return classes

    def get_functions(self) -> list[dict]:
        """Get all top-level functions with their docstrings."""
        if not self.tree:
            return []

        functions = []
        for node in self.tree.body:
            if isinstance(node, ast.FunctionDef):
                functions.append({
                    "name": node.name,
                    "docstring": ast.get_docstring(node),
                    "args": [arg.arg for arg in node.args.args],
                    "lineno": node.lineno
                })
        return functions


def analyze_project(project_path: Path) -> dict:
    """Analyze a project and extract documentation info."""
    project_path = Path(project_path)
    # Path(".").name is '' — resolve to an absolute path first so passing
    # "." (the common case) still yields the real directory name.
    resolved_name = project_path.resolve().name

    info = {
        "name": resolved_name,
        "type": get_project_type(project_path),
        "files": [],
        "classes": [],
        "functions": [],
        "readme_exists": (project_path / "README.md").exists(),
    }

    # Analyze Python files
    python_files = find_python_files(project_path)
    for py_file in python_files:
        # Skip hidden dirs and venv
        if any(part.startswith('.') or part in ('venv', '.venv', '__pycache__', 'node_modules')
               for part in py_file.parts):
            continue

        analyzer = PythonAnalyzer(py_file)
        rel_path = py_file.relative_to(project_path)

        file_info = {
            "path": str(rel_path),
            "docstring": analyzer.get_module_docstring(),
        }
        info["files"].append(file_info)

        for cls in analyzer.get_classes():
            cls["file"] = str(rel_path)
            info["classes"].append(cls)

        for func in analyzer.get_functions():
            func["file"] = str(rel_path)
            info["functions"].append(func)

    return info


def generate_structure_tree(project_path: Path, max_depth: int = 3) -> str:
    """Generate a tree view of project structure."""
    project_path = Path(project_path)
    lines = [project_path.name + "/"]

    def add_items(path: Path, prefix: str = "", depth: int = 0):
        if depth >= max_depth:
            return

        items = sorted(path.iterdir(), key=lambda x: (x.is_file(), x.name))
        items = [i for i in items if not i.name.startswith('.')
                 and i.name not in ('__pycache__', 'node_modules', '.venv', 'venv', '.git')]

        for i, item in enumerate(items):
            is_last = i == len(items) - 1
            connector = "└── " if is_last else "├── "
            lines.append(prefix + connector + item.name + ("/" if item.is_dir() else ""))

            if item.is_dir():
                extension = "    " if is_last else "│   "
                add_items(item, prefix + extension, depth + 1)

    add_items(project_path)
    return "\n".join(lines)


